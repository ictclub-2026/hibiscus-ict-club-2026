/**
 * Resolves a displayable avatar URL for any user-like object.
 * Returns the uploaded avatar if present, otherwise a deterministic
 * initials-based URL from a free CDN avatar service.
 */
export function resolveMemberAvatar(user: {
  avatar?: string;
  id?: string;
  fullName?: string;
  email?: string;
  username?: string;
}): string {
  if (user.avatar) return user.avatar;
  const name = user.fullName || user.username || user.email || "Member";
  const encoded = encodeURIComponent(name);
  return `https://api.dicebear.com/9.x/initials/svg?seed=${encoded}&backgroundColor=e11d48,8b5cf6,0891b2,059669,d97706&fontColor=ffffff&fontSize=42`;
}